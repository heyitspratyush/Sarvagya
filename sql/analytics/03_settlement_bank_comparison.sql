
WITH bank_reference_counts AS (
    SELECT
        BANK_REFERENCE,
        COUNT(*) AS BANK_REFERENCE_COUNT
    FROM SARVAGYA.BANK_TRANSACTIONS
    GROUP BY BANK_REFERENCE
)

SELECT
    s.BATCH_ID,
    s.CURRENCY AS SETTLEMENT_CURRENCY,
    s.REPORTED_NET_AMOUNT,

    COALESCE(brc.BANK_REFERENCE_COUNT, 0)
        AS BANK_REFERENCE_COUNT,

    b.BANK_TXN_ID,
    b.BANK_REFERENCE,
    b.AMOUNT AS BANK_AMOUNT,
    b.CURRENCY AS BANK_CURRENCY,
    b.TRANSACTION_AT AS BANK_TRANSACTION_AT,

    CASE
        WHEN COALESCE(brc.BANK_REFERENCE_COUNT, 0) > 1
            THEN 'AMBIGUOUS_BANK_REFERENCE'

        WHEN b.BANK_TXN_ID IS NULL
            THEN 'UNVERIFIED'

        WHEN b.CURRENCY <> s.CURRENCY
            THEN 'CURRENCY_MISMATCH'

        WHEN b.AMOUNT <> s.REPORTED_NET_AMOUNT
            THEN 'AMOUNT_MISMATCH'

        ELSE 'MATCHED'
    END AS RECONCILIATION_STATUS,

    CASE
        WHEN COALESCE(brc.BANK_REFERENCE_COUNT, 0) <> 1
            THEN NULL

        WHEN b.BANK_TXN_ID IS NULL
            THEN NULL

        WHEN b.CURRENCY <> s.CURRENCY
            THEN NULL

        ELSE b.AMOUNT - s.REPORTED_NET_AMOUNT
    END AS AMOUNT_DIFFERENCE

FROM SARVAGYA.SETTLEMENTS AS s

LEFT JOIN bank_reference_counts AS brc
    ON s.BATCH_ID = brc.BANK_REFERENCE

LEFT JOIN SARVAGYA.BANK_TRANSACTIONS AS b
    ON s.BATCH_ID = b.BANK_REFERENCE

ORDER BY s.BATCH_ID, b.BANK_TXN_ID;
