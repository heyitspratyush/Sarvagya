WITH BATCH_TIMING AS (
    SELECT
        S.BATCH_ID,
        CASE WHEN S.SETTLED_AT IS NULL THEN 'UNVERIFIED'
             WHEN CAST(S.SETTLED_AT AS DATE) > S.EXPECTED_SETTLEMENT_DATE THEN 'AFTER_EXPECTED_DATE'
             ELSE 'ON_OR_BEFORE_EXPECTED_DATE' END AS TIMING_RESULT,
        CASE WHEN S.SETTLED_AT IS NOT NULL
              AND CAST(S.SETTLED_AT AS DATE) > S.EXPECTED_SETTLEMENT_DATE
             THEN CAST(S.SETTLED_AT AS DATE) - S.EXPECTED_SETTLEMENT_DATE END AS CALENDAR_DAY_DELAY,
        COUNT(ST.PROCESSOR_TXN_ID) AS SETTLEMENT_ENTRY_COUNT
    FROM SARVAGYA.SETTLEMENTS S
    LEFT JOIN SARVAGYA.SETTLEMENT_TRANSACTIONS ST ON ST.BATCH_ID = S.BATCH_ID
    WHERE S.BATCH_ID LIKE {batch_prefix}
    GROUP BY S.BATCH_ID, S.EXPECTED_SETTLEMENT_DATE, CAST(S.SETTLED_AT AS DATE), S.SETTLED_AT
)
SELECT TIMING_RESULT, COUNT(*) AS BATCH_COUNT,
       SUM(CALENDAR_DAY_DELAY) AS TOTAL_CALENDAR_DAY_DELAY,
       SUM(SETTLEMENT_ENTRY_COUNT) AS SETTLEMENT_ENTRY_COUNT
FROM BATCH_TIMING
GROUP BY TIMING_RESULT;
