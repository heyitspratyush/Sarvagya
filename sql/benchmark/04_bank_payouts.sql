WITH PAYOUTS AS (
    SELECT
        B.BANK_REFERENCE,
        COUNT(*) AS CANDIDATE_COUNT,
        SUM(B.AMOUNT) AS AGGREGATED_CANDIDATE_AMOUNT,
        MIN(B.AMOUNT) AS ONLY_CANDIDATE_AMOUNT,
        MIN(B.CURRENCY) AS CURRENCY
    FROM SARVAGYA.BANK_TRANSACTIONS B
    WHERE B.BANK_TXN_ID LIKE {bank_prefix}
    GROUP BY B.BANK_REFERENCE
), RESULTS AS (
    SELECT
        CASE WHEN COALESCE(P.CANDIDATE_COUNT, 0) = 0 THEN 'NO_BANK_REFERENCE'
             WHEN P.CANDIDATE_COUNT = 1 THEN 'UNIQUE_BANK_REFERENCE'
             ELSE 'AMBIGUOUS_BANK_REFERENCE' END AS BANK_RESULT,
        CASE WHEN P.CANDIDATE_COUNT = 1 AND P.CURRENCY = S.CURRENCY
             THEN P.ONLY_CANDIDATE_AMOUNT - S.REPORTED_NET_AMOUNT END AS SIGNED_DIFFERENCE
    FROM SARVAGYA.SETTLEMENTS S
    LEFT JOIN PAYOUTS P ON P.BANK_REFERENCE = S.BATCH_ID
    WHERE S.BATCH_ID LIKE {batch_prefix}
)
SELECT BANK_RESULT, COUNT(*) AS BATCH_COUNT,
       SUM(CASE WHEN SIGNED_DIFFERENCE = 0 THEN 1 ELSE 0 END) AS EXACT_AMOUNT_MATCH_COUNT,
       SUM(SIGNED_DIFFERENCE) AS UNIQUE_SIGNED_DIFFERENCE_TOTAL
FROM RESULTS
GROUP BY BANK_RESULT;
