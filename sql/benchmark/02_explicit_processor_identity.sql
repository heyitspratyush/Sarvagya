WITH ATTEMPTS AS (
    SELECT ATTEMPT_ID, ORDER_ID, MERCHANT_PAYMENT_REF
    FROM SARVAGYA.PAYMENT_ATTEMPTS
    WHERE ATTEMPT_ID LIKE {attempt_prefix}
), CANDIDATES AS (
    SELECT
        A.ATTEMPT_ID,
        COUNT(DISTINCT P.PROCESSOR_TXN_ID) AS CANDIDATE_COUNT,
        SUM(CASE WHEN P.TRANSACTION_STATUS = 'CAPTURED' THEN 1 ELSE 0 END) AS CAPTURED_CANDIDATES
    FROM ATTEMPTS A
    LEFT JOIN SARVAGYA.PROCESSOR_TRANSACTIONS P
      ON P.PROCESSOR_TXN_ID LIKE {processor_prefix}
     AND ((P.ORDER_ID = A.ORDER_ID AND P.ORDER_ID IS NOT NULL)
       OR (P.MERCHANT_PAYMENT_REF = A.MERCHANT_PAYMENT_REF
           AND P.MERCHANT_PAYMENT_REF IS NOT NULL))
     AND (A.ORDER_ID IS NULL OR P.ORDER_ID IS NULL OR P.ORDER_ID = A.ORDER_ID)
     AND (A.MERCHANT_PAYMENT_REF IS NULL OR P.MERCHANT_PAYMENT_REF IS NULL
          OR P.MERCHANT_PAYMENT_REF = A.MERCHANT_PAYMENT_REF)
    GROUP BY A.ATTEMPT_ID
)
SELECT
    CASE WHEN CANDIDATE_COUNT = 0 THEN 'NO_EXPLICIT_CANDIDATE'
         WHEN CANDIDATE_COUNT = 1 THEN 'ONE_EXPLICIT_CANDIDATE'
         ELSE 'MULTIPLE_EXPLICIT_CANDIDATES' END AS IDENTITY_RESULT,
    COUNT(*) AS ATTEMPT_COUNT,
    SUM(CAPTURED_CANDIDATES) AS CAPTURED_CANDIDATE_COUNT
FROM CANDIDATES
GROUP BY CASE WHEN CANDIDATE_COUNT = 0 THEN 'NO_EXPLICIT_CANDIDATE'
              WHEN CANDIDATE_COUNT = 1 THEN 'ONE_EXPLICIT_CANDIDATE'
              ELSE 'MULTIPLE_EXPLICIT_CANDIDATES' END;
