WITH ENTRY_AMOUNTS AS (
    SELECT
        ST.BATCH_ID,
        SUM(CASE WHEN P.TRANSACTION_STATUS = 'CAPTURED'
                  AND P.CURRENCY = 'INR' THEN P.TRANSACTION_AMOUNT ELSE 0 END) AS ENTRY_GROSS,
        COUNT(DISTINCT ST.PROCESSOR_TXN_ID) AS ENTRY_COUNT
    FROM SARVAGYA.SETTLEMENT_TRANSACTIONS ST
    LEFT JOIN SARVAGYA.PROCESSOR_TRANSACTIONS P
      ON P.PROCESSOR_TXN_ID = ST.PROCESSOR_TXN_ID
    WHERE ST.BATCH_ID LIKE {batch_prefix}
    GROUP BY ST.BATCH_ID
), BATCH_RESULTS AS (
    SELECT
        COALESCE(E.ENTRY_GROSS, 0) AS ENTRY_GROSS,
        S.GROSS_AMOUNT AS REPORTED_GROSS,
        S.FEE_AMOUNT,
        S.REFUND_AMOUNT,
        S.CHARGEBACK_AMOUNT,
        S.ADJUSTMENT_AMOUNT,
        COALESCE(E.ENTRY_GROSS, 0) - S.FEE_AMOUNT - S.REFUND_AMOUNT
            - S.CHARGEBACK_AMOUNT + S.ADJUSTMENT_AMOUNT AS EXPECTED_NET,
        S.REPORTED_NET_AMOUNT,
        (COALESCE(E.ENTRY_GROSS, 0) - S.FEE_AMOUNT - S.REFUND_AMOUNT
            - S.CHARGEBACK_AMOUNT + S.ADJUSTMENT_AMOUNT) - S.REPORTED_NET_AMOUNT AS SIGNED_DIFFERENCE,
        COALESCE(E.ENTRY_COUNT, 0) AS SETTLEMENT_ENTRY_COUNT
    FROM SARVAGYA.SETTLEMENTS S
    LEFT JOIN ENTRY_AMOUNTS E ON E.BATCH_ID = S.BATCH_ID
    WHERE S.BATCH_ID LIKE {batch_prefix}
)
SELECT
    CASE WHEN SIGNED_DIFFERENCE = 0 THEN 'MATCH' ELSE 'AMOUNT_DIFFERENCE' END AS FINANCIAL_RESULT,
    COUNT(*) AS BATCH_COUNT,
    SUM(ENTRY_GROSS) AS ENTRY_GROSS_TOTAL,
    SUM(REPORTED_GROSS) AS REPORTED_GROSS_TOTAL,
    SUM(EXPECTED_NET) AS EXPECTED_NET_TOTAL,
    SUM(REPORTED_NET_AMOUNT) AS REPORTED_NET_TOTAL,
    SUM(SIGNED_DIFFERENCE) AS SIGNED_DIFFERENCE_TOTAL,
    SUM(SETTLEMENT_ENTRY_COUNT) AS ENTRY_COUNT
FROM BATCH_RESULTS
GROUP BY CASE WHEN SIGNED_DIFFERENCE = 0 THEN 'MATCH' ELSE 'AMOUNT_DIFFERENCE' END;
