SELECT
    COUNT(*) AS ATTEMPT_COUNT,
    COUNT(DISTINCT ORDER_ID) AS ORDER_COUNT,
    SUM(CASE WHEN ATTEMPT_STATUS = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESS_STATUS_COUNT,
    SUM(CASE WHEN ATTEMPT_STATUS = 'FAILED' THEN 1 ELSE 0 END) AS FAILED_STATUS_COUNT,
    SUM(CASE WHEN ATTEMPT_STATUS IS NULL THEN 1 ELSE 0 END) AS NULL_STATUS_COUNT
FROM SARVAGYA.PAYMENT_ATTEMPTS
WHERE ATTEMPT_ID LIKE {attempt_prefix};
