
CREATE TABLE IF NOT EXISTS SARVAGYA.RECONCILIATION_FINDINGS (
    FINDING_ID VARCHAR(50) NOT NULL,
    FINDING_TYPE VARCHAR(40) NOT NULL,
    CLASSIFICATION VARCHAR(40) NOT NULL,
    RESOLUTION_STATUS VARCHAR(20) NOT NULL,
    EXPECTED_AMOUNT DECIMAL(12,2),
    OBSERVED_AMOUNT DECIMAL(12,2),
    DIFFERENCE_AMOUNT DECIMAL(12,2),
    CURRENCY CHAR(3),
    EVIDENCE_SUMMARY VARCHAR(2000),
    LIMITATION VARCHAR(2000),
    CREATED_AT TIMESTAMP NOT NULL,
    EXPECTED_AT TIMESTAMP,
    OBSERVED_AT TIMESTAMP,
    DELAY_MINUTES DECIMAL(12,2),
    PRIMARY KEY (FINDING_ID)
);
