
CREATE TABLE IF NOT EXISTS SARVAGYA.PROCESSOR_TRANSACTIONS (
    PROCESSOR_TXN_ID VARCHAR(50) NOT NULL,
    PROCESSOR_NAME VARCHAR(50) NOT NULL,
    ORDER_ID VARCHAR(50),
    MERCHANT_PAYMENT_REF VARCHAR(100),
    TRANSACTION_AMOUNT DECIMAL(12,2) NOT NULL,
    CURRENCY CHAR(3) NOT NULL,
    TRANSACTION_STATUS VARCHAR(20) NOT NULL,
    TRANSACTION_AT TIMESTAMP NOT NULL,
    PRIMARY KEY (PROCESSOR_TXN_ID)
);
