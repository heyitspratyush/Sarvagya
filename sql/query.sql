
SELECT
    o.ORDER_ID,
    o.ORDER_AMOUNT AS EXPECTED_AMOUNT,
    o.CURRENCY,

    COUNT(DISTINCT p.PROCESSOR_TXN_ID)
        AS CONFIRMED_COLLECTION_COUNT,

    SUM(p.TRANSACTION_AMOUNT)
        AS OBSERVED_COLLECTED_AMOUNT,

    SUM(p.TRANSACTION_AMOUNT) - o.ORDER_AMOUNT
        AS DIFFERENCE_AMOUNT

FROM SARVAGYA.ORDERS o

JOIN SARVAGYA.PROCESSOR_TRANSACTIONS p
    ON p.ORDER_ID = o.ORDER_ID

WHERE o.ORDER_ID = 'SL-GT01-ORDER'
  AND p.TRANSACTION_STATUS = 'CAPTURED'
  AND p.CURRENCY = o.CURRENCY

GROUP BY
    o.ORDER_ID,
    o.ORDER_AMOUNT,
    o.CURRENCY;
